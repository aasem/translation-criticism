"""Command line:

    python -m tc_core validate [ROOT]          validate every report (exit 1 on errors)
    python -m tc_core normalize FILE... [--write]
    python -m tc_core score FILE...            print the summary as JSON
    python -m tc_core segment FILE|-          source segments by the rule, as JSON (a report file, or plain text on stdin)
    python -m tc_core compare ID [ROOT]        print a comparison's analysis as JSON
    python -m tc_core build-js [ROOT]          regenerate assets/method.js from method.json and the schema
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from .spec import comparison_schema, method, report_schema
from .normalize import canonical, dumps, normalize_comparison
from .scoring import summary
from .validate import validate_repo

REPO = Path(__file__).resolve().parents[2]


def js_module() -> str:
    m = json.dumps(method(), indent=2, ensure_ascii=False)
    s = json.dumps(report_schema(), indent=2, ensure_ascii=False)
    c = json.dumps(comparison_schema(), indent=2, ensure_ascii=False)
    return ("// Generated by `python -m tc_core build-js` from core/tc_core/method.json and\n"
            "// core/tc_core/schema/*.schema.json. Do not edit by hand.\n"
            f"export const METHOD = {m};\n\nexport const SCHEMA = {s};\n\nexport const CMP_SCHEMA = {c};\n")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="tc_core")
    sub = ap.add_subparsers(dest="cmd", required=True)
    v = sub.add_parser("validate"); v.add_argument("root", nargs="?", default=str(REPO))
    v.add_argument("--json", action="store_true")
    n = sub.add_parser("normalize"); n.add_argument("files", nargs="+"); n.add_argument("--write", action="store_true")
    s = sub.add_parser("score"); s.add_argument("files", nargs="+")
    sg = sub.add_parser("segment"); sg.add_argument("file")
    cp = sub.add_parser("compare"); cp.add_argument("id"); cp.add_argument("root", nargs="?", default=str(REPO))
    b = sub.add_parser("build-js"); b.add_argument("root", nargs="?", default=str(REPO))
    b.add_argument("--check", action="store_true", help="fail if assets/method.js is out of date")
    a = ap.parse_args(argv)

    if a.cmd == "validate":
        res = validate_repo(a.root)
        errors = sum(i.level == "error" for xs in res.values() for i in xs)
        if a.json:
            print(json.dumps({f: [i.__dict__ for i in xs] for f, xs in res.items()}, indent=2, ensure_ascii=False))
        else:
            for f, xs in res.items():
                print(f"{f}: {'ok' if not xs else ''}")
                for i in xs:
                    print("  " + str(i))
            print(f"\n{errors} error(s), {sum(len(x) for x in res.values()) - errors} warning(s)")
        return 1 if errors else 0
    if a.cmd == "normalize":
        for f in a.files:
            p = Path(f); text = p.read_text(encoding="utf-8")
            data = json.loads(text)
            r, notes = (normalize_comparison(data), []) if "members" in data else canonical(data)
            out = dumps(r)
            print(f"{f}: {'unchanged' if out == text else 'changed'}")
            for x in notes:
                print("  " + x)
            if a.write and out != text:
                p.write_text(out, encoding="utf-8")
        return 0
    if a.cmd == "score":
        print(json.dumps([summary(canonical(json.loads(Path(f).read_text(encoding="utf-8")))[0]) for f in a.files],
                         indent=2, ensure_ascii=False))
        return 0
    if a.cmd == "segment":
        from .segment import departures, segment
        raw = sys.stdin.read() if a.file == "-" else Path(a.file).read_text(encoding="utf-8")
        try:
            r = json.loads(raw)
        except ValueError:
            r = None
        text = r["source"]["text"] if isinstance(r, dict) else raw
        out = {"rule": method()["segmentation"]["rule"], "segments": [{"n": i + 1, "source": s} for i, s in enumerate(segment(text))]}
        if isinstance(r, dict) and r.get("segments"):
            out["departures"] = departures(r)
        print(json.dumps(out, indent=2, ensure_ascii=False))
        return 0
    if a.cmd == "compare":
        from .compare import analyse, consistency
        root = Path(a.root)
        c = json.loads((root / "comparisons" / f"{a.id}.json").read_text(encoding="utf-8"))
        rs = [canonical(json.loads((root / "reports" / f"{m['id']}.json").read_text(encoding="utf-8")))[0] for m in c["members"]]
        print(json.dumps({**analyse(c, rs), "consistency": consistency(c, rs)}, indent=2, ensure_ascii=False))
        return 0
    if a.cmd == "build-js":
        p = Path(a.root) / "assets" / "method.js"
        js = js_module()
        if a.check:
            ok = p.exists() and p.read_text(encoding="utf-8") == js
            print("assets/method.js is " + ("up to date" if ok else "out of date: run python -m tc_core build-js"))
            return 0 if ok else 1
        p.write_text(js, encoding="utf-8"); print(f"wrote {p}")
        return 0
    return 2


if __name__ == "__main__":
    sys.exit(main())
